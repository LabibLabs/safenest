class Doctor {
  String name;
  String hospitalName;
  String specialist;
  String reason;
  String time; // in 24 hour formate
  String date;
  String month;
  String year;

  Doctor({
    required this.name,
    required this.hospitalName,
    required this.specialist,
    required this.reason,
    required this.time,
    required this.date,
    required this.month,
    required this.year,
});
}